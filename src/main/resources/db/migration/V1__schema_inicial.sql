-- Esquema inicial. SQL portável: roda igual em H2 (dev/testes) e PostgreSQL.
-- Enums viram varchar + CHECK (o tipo ENUM nativo existe só no H2).

create table mesa (
    id     bigint generated by default as identity primary key,
    numero integer     not null unique,
    status varchar(20) not null check (status in ('LIVRE', 'OCUPADA'))
);

create table insumo (
    id             bigint generated by default as identity primary key,
    versao         bigint         not null,
    nome           varchar(255)   not null unique,
    unidade        varchar(10)    not null,
    estoque_atual  numeric(14, 3) not null,
    estoque_minimo numeric(14, 3) not null,
    custo_unitario numeric(14, 4) not null
);

create table produto (
    id        bigint generated by default as identity primary key,
    nome      varchar(255)   not null unique,
    categoria varchar(255)   not null,
    preco     numeric(12, 2) not null,
    praca     varchar(20)    not null check (praca in ('BAR', 'COZINHA', 'SOBREMESA')),
    ativo     boolean        not null
);

create table item_ficha (
    id         bigint generated by default as identity primary key,
    produto_id bigint         not null references produto (id),
    insumo_id  bigint         not null references insumo (id),
    quantidade numeric(14, 3) not null
);

create table caixa (
    id             bigint generated by default as identity primary key,
    status         varchar(20)    not null check (status in ('ABERTO', 'FECHADO')),
    valor_abertura numeric(12, 2) not null,
    operador       varchar(255),
    aberto_em      timestamp(6) with time zone not null,
    fechado_em     timestamp(6) with time zone,
    valor_contado  numeric(12, 2),
    -- TRUE enquanto aberto, NULL depois de fechado: a unicidade garante um único caixa aberto
    aberto_unico   boolean unique
);

create table comanda (
    id                bigint generated by default as identity primary key,
    mesa_id           bigint       not null references mesa (id),
    status            varchar(20)  not null check (status in ('ABERTA', 'FECHADA')),
    percentual_servico numeric(5, 2) not null,
    aberta_em         timestamp(6) with time zone not null,
    fechada_em        timestamp(6) with time zone
);

create table item_comanda (
    id             bigint generated by default as identity primary key,
    comanda_id     bigint         not null references comanda (id),
    produto_id     bigint         not null references produto (id),
    quantidade     integer        not null,
    preco_unitario numeric(12, 2) not null,
    custo_unitario numeric(14, 4) not null,
    observacao     varchar(255),
    status         varchar(20)    not null check (status in ('PENDENTE', 'EM_PREPARO', 'PRONTO', 'ENTREGUE', 'CANCELADO')),
    praca          varchar(20)    not null check (praca in ('BAR', 'COZINHA', 'SOBREMESA')),
    criado_em      timestamp(6) with time zone not null,
    atualizado_em  timestamp(6) with time zone,
    version        bigint default 0 not null
);

-- Quanto de cada insumo saiu do estoque no pedido do item (base do estorno e da perda)
create table item_consumo (
    item_id    bigint         not null references item_comanda (id),
    insumo_id  bigint         not null,
    quantidade numeric(14, 3) not null,
    primary key (item_id, insumo_id)
);

create table pagamento (
    id             bigint generated by default as identity primary key,
    comanda_id     bigint         not null references comanda (id),
    caixa_id       bigint         not null references caixa (id),
    forma          varchar(20)    not null check (forma in ('DINHEIRO', 'PIX', 'DEBITO', 'CREDITO')),
    valor          numeric(12, 2) not null,
    valor_recebido numeric(12, 2) not null,
    pagador        varchar(255),
    pago_em        timestamp(6) with time zone not null
);

create table movimento_estoque (
    id         bigint generated by default as identity primary key,
    insumo_id  bigint         not null references insumo (id),
    tipo       varchar(20)    not null check (tipo in ('ENTRADA', 'SAIDA_VENDA', 'ESTORNO', 'PERDA')),
    quantidade numeric(14, 3) not null,
    referencia varchar(255),
    criado_em  timestamp(6) with time zone not null
);

create index idx_item_comanda_comanda on item_comanda (comanda_id);
create index idx_item_comanda_fila on item_comanda (praca, status);
create index idx_pagamento_comanda on pagamento (comanda_id);
create index idx_pagamento_caixa on pagamento (caixa_id);
create index idx_movimento_insumo on movimento_estoque (insumo_id);
create index idx_comanda_status on comanda (status);
